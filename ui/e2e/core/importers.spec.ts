import { randomUUID } from 'node:crypto';
import { test, expect, editJson, freshSbom, hostRepository, apiURL } from '../support';

test('importer lifecycle, configuration validation, optimistic locking, and local run reports', async ({ page, request, owned, allowedApiErrors }) => {
  test.setTimeout(120_000);
  const name = `e2e-${randomUUID()}`;
  allowedApiErrors.push(`/api/v3/importer/${name}`);
  const data = await freshSbom(name);
  const url = await hostRepository(data, owned);
  const config = { http: { source: url, discovery: { type: 'pulp' }, fetchRetries: 0, period: '1d', disabled: true, description: 'e2e local source' } };
  await page.goto('/importers');
  await page.getByRole('button', { name: 'Add importer', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('button', { name: 'Add', exact: true })).toBeDisabled();
  await dialog.getByRole('textbox', { name: 'Name', exact: true }).fill(name);
  await editJson(dialog, '{invalid');
  await dialog.getByRole('button', { name: 'Add', exact: true }).click();
  await expect(dialog.getByText(/Invalid JSON/)).toBeVisible();
  await editJson(dialog, JSON.stringify(config));
  owned.importers.push(name);
  await dialog.getByRole('button', { name: 'Add', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('row').filter({ hasText: name }).getByRole('link', { name, exact: true }).click();
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  await expect(page.getByText('Disabled')).toBeVisible();
  await page.getByRole('button', { name: 'Configuration', exact: true }).click();
  await expect(page.locator('.monaco-editor').first()).toBeVisible();
  config.http.description = 'changed through API';
  const updated = await request.put(`${apiURL}/api/v3/importer/${name}`, { data: config });
  expect(updated.ok(), await updated.text()).toBeTruthy();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByText(/The importer changed since it was loaded/)).toBeVisible();
  await page.getByRole('button', { name: 'Reload', exact: true }).click();
  await expect(page.locator('.trustify-config-editor').first()).toContainText('changed through API');
  config.http.description = 'changed through UI';
  await editJson(page, JSON.stringify(config));
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByText('Configuration saved')).toBeVisible();
  await page.reload();
  await expect(page.getByText('changed through UI')).toBeVisible();
  await page.getByRole('button', { name: 'Actions', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Enable', exact: true }).click();
  await expect(page.getByText('Disabled')).toHaveCount(0);
  await page.getByRole('button', { name: 'Actions', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Run now', exact: true }).click();
  await expect.poll(async () => {
    const response = await request.get(`${apiURL}/api/v3/importer/${name}/report`);
    return (await response.json()).items.length;
  }, { timeout: 60_000 }).toBeGreaterThan(0);
  await page.getByRole('button', { name: 'Reports', exact: true }).click();
  await expect(page.getByRole('columnheader', { name: 'Items', exact: true })).toBeVisible();
  const sboms = await request.get(`${apiURL}/api/v3/sbom`, { params: { q: name } });
  const results = (await sboms.json()).items;
  expect(results).toHaveLength(1);
  owned.sboms.push(results[0].id);
  await page.getByRole('button', { name: 'Actions', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Disable', exact: true }).click();
  await expect(page.getByText('Disabled')).toBeVisible();
  await page.getByRole('button', { name: 'Actions', exact: true }).click();
  await page.getByRole('menuitem', { name: /Delete$/ }).click();
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Importers', exact: true })).toBeVisible();
  await expect(page.getByRole('row').filter({ hasText: name })).toHaveCount(0);
});
